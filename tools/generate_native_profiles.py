"""构建期将校验过的官方配置转为原生 JSON；终端不需要 Python/YAML 库。"""
import argparse
import hashlib
import json
from pathlib import Path
import yaml
from prepare_models import ROOT, valid


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', type=Path)
    args = parser.parse_args()
    manifest = json.loads((ROOT/'models.lock.json').read_text(encoding='utf-8'))
    models = [m for m in manifest['models'] if m['release_enabled']]
    rows = []
    downloads = []
    for family, tier in sorted({(m['family'], m['tier']) for m in models}):
        pair = {m['role']: m for m in models if (m['family'], m['tier']) == (family, tier)}
        roots = [ROOT/base/family/tier for base in ('dist/models', 'downloads/models')]
        root = next((p for p in roots if all(valid(p/role/f['name'], f)
                    for role, m in pair.items() for f in m['files'])), None)
        if root is None:
            raise RuntimeError(f'Missing verified model pair: {family}/{tier}; run prepare_models explicitly')
        configs = {r: yaml.safe_load((root/r/'inference.yml').read_text(encoding='utf-8')) for r in pair}
        det, rec = configs['det'], configs['rec']
        if det['PostProcess']['name'] != 'DBPostProcess' or rec['PostProcess']['name'] != 'CTCLabelDecode':
            raise ValueError('Unsupported processing')
        norm = next(x['NormalizeImage'] for x in det['PreProcess']['transform_ops'] if 'NormalizeImage' in x)
        shape = next(x['RecResizeImg']['image_shape'] for x in rec['PreProcess']['transform_ops'] if 'RecResizeImg' in x)
        if norm['scale'] != '1./255.' or shape[0] != 3:
            raise ValueError('Unsupported normalization or channels')
        profile = dict(family=family, tier=tier, mean=norm['mean'], std=norm['std'],
                       threshold=det['PostProcess']['thresh'], box_threshold=det['PostProcess']['box_thresh'],
                       unclip=det['PostProcess']['unclip_ratio'], candidates=det['PostProcess']['max_candidates'],
                       rec_height=shape[1], rec_width=shape[2],
                       dictionary=['']+rec['PostProcess']['character_dict']+[' '])
        data = (json.dumps(profile, ensure_ascii=False, separators=(',', ':'))+'\n').encode('utf-8')
        (root/'profile.json').write_bytes(data)
        # 配置和权重的期望哈希编入 worker，防止配置与模型意外混配。
        hashes = [hashlib.sha256(data).hexdigest()]
        for role in ('det', 'rec'):
            hashes.extend(next(f['sha256'] for f in pair[role]['files'] if f['name'] == name)
                          for name in ('inference.onnx', 'inference.yml'))
        revision = pair['det']['revision'] + '-' + pair['rec']['revision']
        rows.append('{' + ','.join(json.dumps(s) for s in [family, tier, *hashes, revision]) + '}')
        for role, model in pair.items():
            for f in model['files']:
                downloads.append('{' + ','.join(json.dumps(s) for s in
                    [family, tier, role+'/'+f['name'], f['url'], f['sha256']]) + ','+str(f['size'])+'ULL}')
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text('#pragma once\n// Generated by generate_native_profiles.py.\n'
        'struct ModelHashes { const char *family, *tier, *profile, *det, *det_config, *rec, *rec_config, *revision; };\n'
        'inline constexpr ModelHashes kModels[] = {\n'+',\n'.join(rows)+'\n};\n'
        'struct DownloadFile { const char *family, *tier, *name, *url, *sha256; unsigned long long size; };\n'
        'inline constexpr DownloadFile kDownloads[] = {\n'+',\n'.join(downloads)+'\n};\n', encoding='utf-8')
    print('Generated verified profiles for', len(rows), 'model pairs')


if __name__ == '__main__':
    main()
